#!/usr/bin/env bash
# Install a Termux:Widget home-screen shortcut for the unofficial headless starter.
# Run once FROM Termux after setup. Does not build or install any custom APK.
#
#   bash install-termux-widget.sh
#
# Requires Termux:Widget from F-Droid:
#   https://f-droid.org/packages/com.termux.widget/
#
# Termux:Widget's lean launch path breaks on:
#   - shortcut filenames with spaces (e.g. Chinese label + space)
#   - #!/usr/bin/env bash (env may be missing / mis-resolve under Widget)
# So we install a thin ASCII-named wrapper with Termux's absolute bash path
# that execs start-from-termux.sh by absolute path.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
STARTER="${ROOT}/start-from-termux.sh"
SHORTCUTS_DIR="${HOME}/.shortcuts"
# Termux:Widget shows the file name as the button label — keep it ASCII, no spaces.
SHORTCUT_NAME="start-antigravity"
SHORTCUT_PATH="${SHORTCUTS_DIR}/${SHORTCUT_NAME}"
# Legacy name from the first installer (space + Chinese broke Widget + env shebang).
LEGACY_SHORTCUT_PATH="${SHORTCUTS_DIR}/启动 Antigravity"

log() { printf '%s\n' "$*"; }
die() { printf '%s\n' "$*" >&2; exit 1; }

if [ ! -f "$STARTER" ]; then
  die "Missing ${STARTER}. Keep install-termux-widget.sh next to start-from-termux.sh."
fi

# Soft hint only: Widget shortcuts live in the Termux home, not in Debian.
if [ -f /etc/debian_version ] && [ -z "${PREFIX:-}" ] && [ -z "${TERMUX_VERSION:-}" ] && [ ! -d /data/data/com.termux ]; then
  log "Note: install the shortcut from a Termux session so ~/.shortcuts is the Termux home."
fi

# Prefer $PREFIX/bin/bash when running inside Termux; else the standard Termux path.
if [ -n "${PREFIX:-}" ] && [ -x "${PREFIX}/bin/bash" ]; then
  TERMUX_BASH="${PREFIX}/bin/bash"
elif [ -x /data/data/com.termux/files/usr/bin/bash ]; then
  TERMUX_BASH="/data/data/com.termux/files/usr/bin/bash"
else
  TERMUX_BASH="/data/data/com.termux/files/usr/bin/bash"
  log "Warning: ${TERMUX_BASH} not found yet; writing that shebang anyway (install Termux bash first)."
fi

mkdir -p "$SHORTCUTS_DIR"

# Idempotent cleanup of the broken legacy shortcut name.
if [ -e "$LEGACY_SHORTCUT_PATH" ]; then
  rm -f "$LEGACY_SHORTCUT_PATH"
  log "Removed legacy shortcut: ${LEGACY_SHORTCUT_PATH}"
fi

# Thin Widget entrypoint: absolute Termux bash + exec real starter (no env shebang).
# start-from-termux.sh may keep #!/usr/bin/env bash for interactive Termux use;
# Widget must not depend on that path.
cat >"$SHORTCUT_PATH" <<EOF
#!${TERMUX_BASH}
# Termux:Widget entrypoint — do not use #!/usr/bin/env here.
# Generated by install-termux-widget.sh; re-run that helper after moving the bundle.
exec "${TERMUX_BASH}" "${STARTER}" "\$@"
EOF
chmod 755 "$SHORTCUT_PATH"

# Termux:Widget only lists executable scripts under ~/.shortcuts/
log ""
log "Installed Termux:Widget shortcut:"
log "  ${SHORTCUT_PATH}"
log "  shebang: #!${TERMUX_BASH}"
log "  exec → ${STARTER}"
log ""
log "中文下一步："
log "  1. 从 F-Droid 安装 Termux:Widget（若尚未安装；签名需与 Termux 一致）"
log "     https://f-droid.org/packages/com.termux.widget/"
log "  2. 若桌面已有旧的「启动 Antigravity」小组件，先移除再重新添加"
log "  3. 长按桌面 → 小组件 / Widget → 选 Termux:Widget → 选 start-antigravity"
log "  4. 点 start-antigravity 即可一键启动（默认打开 Web UI）"
log "  5. 若已在跑，再点一次只打印地址并打开浏览器，不会起第二个实例"
log ""
log "English next steps:"
log "  1. Install Termux:Widget from F-Droid if needed (matching Termux signature)"
log "     https://f-droid.org/packages/com.termux.widget/"
log "  2. Remove any old desktop widget (e.g. 「启动 Antigravity」), then add Termux:Widget again"
log "  3. Long-press the home screen → Widgets → Termux:Widget → pick start-antigravity"
log "  4. Tap start-antigravity for one-tap start (opens the Web UI by default)"
log "  5. A second tap while already up only prints URLs / opens the browser"
log ""
log "Manual one-liner (no widget):"
log "  bash ${STARTER}"
log ""
log "Unofficial Termux headless — not an official Android app / APK."
log "Re-run this helper after updating or moving start-from-termux.sh."
